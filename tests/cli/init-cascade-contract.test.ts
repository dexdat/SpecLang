/**
 * Regression test for DF-SPECLANG-1-R4: init scaffolding must produce specs
 * that the real cascade generates code from.
 *
 * The shipped `speclang init` template used to emit `### @block:main
 * @kind:code` (single colon) with a bare ```ts fence. Cascade's parseSpec
 * only recognizes `### @block::NAME @kind:KIND` (double colon), so the block
 * was invisible and cascade exited 0 with "Generated: 0 files" plus
 * "No TypeScript code blocks found in spec" — the most common new-user entry
 * point feeding a pipeline that rejected its own output.
 *
 * These tests escalate through the shipped CLI surface (init) and then the
 * real generator (parseSpec + runCascade), so the old zero-file false-success
 * fails here instead of only in the field.
 *
 * ch:trace row=DF-SPECLANG-1-R4 spec=specs/project-layout.spec.dir/src/templates.ts#generateInitialSpec wave=none:serial-worker test=tests/project-layout.test.ts::init-to-cascade doc=none:code-task evidence=none:worker-local-until-foreman-verifies witness=none:worker-worktree verdict=none:foreman-must-run-judge commit=none:worker-commit memory=none:foreman-writes
 */
import { describe, it, expect, beforeEach, afterEach } from "vitest";
import { execFileSync } from "child_process";
import { mkdtempSync, readFileSync, readdirSync, rmSync, existsSync } from "fs";
import { join } from "path";
import { tmpdir } from "os";
import { parseSpec, runCascade } from "../../src/cascade/index.js";

const CLI = join(process.cwd(), "bin/speclang");

function runInit(cwd: string, args: string[] = []): string {
  return execFileSync(process.execPath, [CLI, "init", "demo", ...args], {
    cwd,
    encoding: "utf-8",
  });
}

function countFence(content: string, language: string): number {
  const re = new RegExp("^```" + language + "\\s*$", "gm");
  return (content.match(re) || []).length;
}

describe("init scaffolding → cascade contract", () => {
  let testDir: string;

  beforeEach(() => {
    testDir = mkdtempSync(join(tmpdir(), "speclang-init-cascade-"));
  });

  afterEach(() => {
    if (testDir && existsSync(testDir)) {
      rmSync(testDir, { recursive: true, force: true });
    }
  });

  it("writes a spec whose code block is the canonical speclang fence", () => {
    runInit(testDir);

    const specPath = join(testDir, "specs", "demo", "demo.spec.md");
    expect(existsSync(specPath)).toBe(true);
    const content = readFileSync(specPath, "utf-8");

    // Canonical header + fence: readable by both the validator parser and
    // cascade's parseSpec.
    expect(content).toMatch(/^### @block::main @kind:code$/m);
    expect(countFence(content, "speclang")).toBeGreaterThanOrEqual(1);

    // No bare ```ts fence and no single-colon block header may ship.
    expect(countFence(content, "ts")).toBe(0);
    expect(countFence(content, "typescript")).toBe(0);
    expect(content).not.toMatch(/^### @block:[^:]/m);
  });

  it("generates a non-empty .ts file through the real cascade path", async () => {
    runInit(testDir);
    const specPath = join(testDir, "specs", "demo", "demo.spec.md");
    const content = readFileSync(specPath, "utf-8");

    // The init output is visible to cascade's parser as a real code block.
    const parsed = parseSpec(content);
    expect(parsed.blocks).toHaveLength(1);
    expect(parsed.blocks[0].name).toBe("main");
    expect(parsed.blocks[0].kind).toBe("code");
    expect(parsed.blocks[0].language).toBe("speclang");
    expect(parsed.blocks[0].code).toContain("Implementation for demo");

    // ...and cascade actually emits code from it (no zero-file false success).
    const result = await runCascade(specPath, { verbose: false });
    expect(result.warning).toBeUndefined();
    expect(result.filesGenerated).toHaveLength(1);

    const generatedPath = result.filesGenerated[0];
    expect(generatedPath.endsWith("main.ts")).toBe(true);
    const generated = readFileSync(generatedPath, "utf-8");
    expect(generated.length).toBeGreaterThan(0);
    expect(generated).toContain("Auto-generated by SpecLang");
    expect(generated).toContain("Implementation for demo");
  });

  it("keeps the same contract for --tiers scaffolding", async () => {
    runInit(testDir, ["--tiers"]);

    const tsSpecPath = join(testDir, "specs", "demo", "demo.spec.ts.md");
    const tsSpec = readFileSync(tsSpecPath, "utf-8");
    expect(tsSpec).toMatch(/^### @block::main @kind:code$/m);
    expect(countFence(tsSpec, "speclang")).toBe(1);
    expect(countFence(tsSpec, "ts")).toBe(0);

    const parsed = parseSpec(tsSpec);
    expect(parsed.blocks).toHaveLength(1);
    expect(parsed.blocks[0].language).toBe("speclang");

    const result = await runCascade(tsSpecPath, { verbose: false });
    expect(result.filesGenerated.length).toBeGreaterThanOrEqual(1);
    const generated = readFileSync(result.filesGenerated[0], "utf-8");
    expect(generated).toContain("Implementation for demo");

    // Tier test specs follow the same fence convention.
    const testSpec = readFileSync(
      join(testDir, "specs", "demo", "demo.spec.test.md"),
      "utf-8"
    );
    expect(countFence(testSpec, "speclang")).toBe(1);
  });

  it("project-layout generateInitialSpec emits the same canonical contract", async () => {
    // The project-init template (`speclang init` for a whole project) had the
    // same defect: single-colon header, no @kind, bare ```typescript fence.
    const { generateInitialSpec } = await import(
      "../../src/project-layout/templates.js"
    );
    const content = generateInitialSpec("my-feature");

    expect(content).toMatch(/^### @block::my-feature-entity @kind:entity$/m);
    expect(countFence(content, "speclang")).toBe(1);
    expect(countFence(content, "typescript")).toBe(0);
  });
});
