#!/usr/bin/env node
/**
 * check_docs_vs_cli_help.js — docs/CLI parity gate.
 *
 * Compares the top-level commands that `node bin/speclang --help` advertises
 * against the CLI reference table in docs/API_REFERENCE.md (§2. CLI) and
 * reports any command the table does not document.
 *
 * Usage:
 *   node scripts/check_docs_vs_cli_help.js
 *   node scripts/check_docs_vs_cli_help.js --docs /tmp/scratch/API_REFERENCE.md
 *
 * Exit codes:
 *   0  every command from --help is documented in the table
 *   1  one or more commands are missing from the table (parity broken)
 *   2  the gate could not run (CLI help failed, docs or CLI section missing)
 *
 * Aliases: a command group like `history|log` counts as documented when any of
 * its names appears in the table; aliases that are not individually listed are
 * reported as non-fatal notes so a real gap is still visible.
 */

'use strict';

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const REPO_ROOT = path.resolve(__dirname, '..');
const CLI_ENTRY = path.join(REPO_ROOT, 'bin', 'speclang');
const DEFAULT_DOCS = path.join(REPO_ROOT, 'docs', 'API_REFERENCE.md');

// Commander's built-in `help [command]` is generated by the framework, not a
// SpecLang product command; it is handled by the `-h, --help` option lines.
const BUILTIN_COMMANDS = new Set(['help']);

function parseArgs(argv) {
  const args = { docs: DEFAULT_DOCS, cli: CLI_ENTRY };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--docs') {
      const v = argv[++i];
      if (!v) throw new Error('--docs requires a path');
      args.docs = path.resolve(v);
    } else if (a === '--cli') {
      const v = argv[++i];
      if (!v) throw new Error('--cli requires a path');
      args.cli = path.resolve(v);
    } else if (a === '-h' || a === '--help') {
      console.log('Usage: node scripts/check_docs_vs_cli_help.js [--docs <file>] [--cli <bin>]');
      process.exit(0);
    } else {
      throw new Error(`unknown argument: ${a}`);
    }
  }
  return args;
}

/** Run `speclang --help` and return the command groups it lists. */
function readCliCommands(cliPath) {
  const res = spawnSync(process.execPath, [cliPath, '--help'], {
    encoding: 'utf8',
    cwd: REPO_ROOT,
  });
  if (res.error) throw new Error(`could not run ${cliPath} --help: ${res.error.message}`);
  if (res.status !== 0) {
    throw new Error(`${cliPath} --help exited ${res.status}: ${(res.stderr || '').trim()}`);
  }
  const out = res.stdout || '';
  const lines = out.split('\n');
  const start = lines.findIndex((l) => l.trim() === 'Commands:');
  if (start === -1) throw new Error('no "Commands:" section in --help output');

  const groups = [];
  for (let i = start + 1; i < lines.length; i++) {
    const line = lines[i];
    if (line.trim() === '') break;
    // A command entry starts in the two-space column; wrapped descriptions are
    // indented far deeper and are skipped.
    const m = line.match(/^ {2}([A-Za-z][A-Za-z0-9-]*(?:\|[A-Za-z][A-Za-z0-9-]*)*)/);
    if (!m) continue;
    const names = m[1].split('|');
    groups.push({ names, primary: names[0], aliases: names.slice(1) });
  }
  if (groups.length === 0) throw new Error('parsed zero commands from --help output');
  return groups;
}

/** Return the set of command names documented in the §2 CLI table. */
function readDocumentedCommands(docsPath) {
  const raw = fs.readFileSync(docsPath, 'utf8');
  const lines = raw.split('\n');
  const start = lines.findIndex((l) => /^##\s+2\.\s+CLI\b/.test(l));
  if (start === -1) throw new Error(`no "## 2. CLI" heading in ${docsPath}`);
  let end = lines.length;
  for (let i = start + 1; i < lines.length; i++) {
    if (/^##\s/.test(lines[i])) {
      end = i;
      break;
    }
  }

  const documented = new Set();
  for (let i = start + 1; i < end; i++) {
    const line = lines[i];
    if (!line.startsWith('|')) continue;
    // Table cells escape pipes as `\|` (markdown requirement), so strip the
    // backslashes before splitting an alias group such as `history\|log`.
    const re = /`speclang\s+([^\s`]+)/g;
    let m;
    while ((m = re.exec(line)) !== null) {
      const token = m[1].replace(/\\/g, '');
      for (const name of token.split('|')) {
        if (name) documented.add(name);
      }
    }
  }
  return documented;
}

function main() {
  let args;
  try {
    args = parseArgs(process.argv.slice(2));
  } catch (err) {
    console.error(`ERROR: ${err.message}`);
    return 2;
  }

  let groups;
  let documented;
  try {
    groups = readCliCommands(args.cli);
    documented = readDocumentedCommands(args.docs);
  } catch (err) {
    console.error(`ERROR: gate could not run: ${err.message}`);
    return 2;
  }

  const product = groups.filter((g) => !BUILTIN_COMMANDS.has(g.primary));
  const skipped = groups.filter((g) => BUILTIN_COMMANDS.has(g.primary)).map((g) => g.primary);
  const missing = [];
  const aliasNotes = [];

  for (const group of product) {
    const hit = [group.primary, ...group.aliases].filter((n) => documented.has(n));
    if (hit.length === 0) {
      missing.push(group.names.join('|'));
      continue;
    }
    for (const alias of group.aliases) {
      if (!documented.has(alias)) aliasNotes.push(`${alias} (documented via ${hit[0]})`);
    }
  }

  const relDocs = path.relative(REPO_ROOT, args.docs) || args.docs;
  console.log('docs/CLI parity check');
  console.log(`  cli:          ${path.relative(REPO_ROOT, args.cli) || args.cli} --help`);
  console.log(`  docs table:   ${relDocs} (§2. CLI)`);
  console.log(`  commands:     ${product.length} from --help, ${documented.size} names in the table`);
  if (skipped.length > 0) console.log(`  skipped:      ${skipped.join(', ')} (framework built-in)`);
  for (const note of aliasNotes) console.log(`  note:         alias ${note}`);

  if (missing.length > 0) {
    console.error(`FAIL: ${missing.length} CLI command(s) missing from the table: ${missing.join(', ')}`);
    return 1;
  }
  console.log(`OK: every command from --help is documented in ${relDocs}`);
  return 0;
}

process.exit(main());
